@pytest.mark.parametrize("case", CASES)
def test_stack_consistency(case: str) -> None:
    report, _ = load_report(case)
    sources = report.get("sources")
    if not isinstance(sources, dict):
        pytest.fail(f"{case}: {report_path(case)}: sources is not an object ({sources!r})")

    problems: list[str] = []
    for key, src in sources.items():
        if not isinstance(src, dict):
            continue
        base = f"sources.{key}"
        stacks = src.get("stacks") or []
        recommended = src.get("recommended_stack")

        if not isinstance(stacks, list):
            problems.append(f"{base}.stacks: expected a list, got {stacks!r}")
            continue
        if not stacks:
            if recommended:
                problems.append(
                    f"{base}.recommended_stack: no stacks are persisted but a recommendation is "
                    f"({str(recommended)[:120]!r})"
                )
            continue
        if not isinstance(recommended, dict):
            problems.append(
                f"{base}.recommended_stack: stacks are persisted but the recommendation is "
                f"{recommended!r}; `download --stack recommended` would fall back to stacks[0]"
            )

        source_id_set = {gid for gid in (src.get("granule_ids") or []) if isinstance(gid, str)}

        for index, stack in enumerate(stacks):
            stack_path = f"{base}.stacks[{index}]"
            if not isinstance(stack, dict):
                problems.append(f"{stack_path}: expected an object, got {stack!r}")
                continue
            missing = [field for field in STACK_FIELDS if field not in stack]
            if missing:
                problems.append(f"{stack_path}: missing required field(s) {missing}")

            track, direction = stack.get("track"), stack.get("direction")
            n_granules = stack.get("n_granules")
            if not isinstance(n_granules, int) or isinstance(n_granules, bool) or n_granules <= 0:
                problems.append(
                    f"{stack_path}.n_granules: expected an int > 0, got {n_granules!r}"
                )
                n_granules = None

            window = date_range(
                case,
                f"{stack_path}.date_range",
                stack.get("date_range"),
                problems,
                allow_none=False,
            )

            mean_interval = stack.get("mean_interval_days")
            n_granules = stack.get("n_granules")
            if is_number(n_granules) and n_granules < 2:
                # A single pair has no consecutive gap to measure, so null is the honest value —
                # but the field must be present and must not be a zero or a made-up number.
                if mean_interval is not None:
                    problems.append(
                        f"{stack_path}.mean_interval_days: a single-granule stack has no gap, so "
                        f"this must be null, got {mean_interval!r}"
                    )
            elif not is_number(mean_interval) or mean_interval <= 0:
                problems.append(
                    f"{stack_path}.mean_interval_days: expected a number > 0, got {mean_interval!r}"
                )

            granule_ids = stack.get("granule_ids")
            if not isinstance(granule_ids, list) or not granule_ids:
                problems.append(
                    f"{stack_path}.granule_ids: expected a non-empty list, got {granule_ids!r}"
                )
                continue
            if len(granule_ids) > STACK_GRANULE_LIMIT:
                problems.append(
                    f"{stack_path}.granule_ids: {len(granule_ids)} ids exceed the module's "
                    f"STACK_GRANULE_LIMIT={STACK_GRANULE_LIMIT}"
                )
            if n_granules is not None and len(granule_ids) > n_granules:
                problems.append(
                    f"{stack_path}.granule_ids: {len(granule_ids)} sampled ids but "
                    f"n_granules is {n_granules}"
                )
            if len(set(granule_ids)) != len(granule_ids):
                duplicates = sorted({gid for gid in granule_ids if granule_ids.count(gid) > 1})
                problems.append(
                    f"{stack_path}.granule_ids: duplicate id(s) {duplicates[:3]!r}"
                )
            if "granule_ids_truncated" in stack and n_granules is not None:
                expected_flag = len(granule_ids) < n_granules
                if stack["granule_ids_truncated"] is not expected_flag:
                    problems.append(
                        f"{stack_path}.granule_ids_truncated: {stack['granule_ids_truncated']!r} "
                        f"but {len(granule_ids)} of {n_granules} ids are present "
                        f"(expected {expected_flag!r})"
                    )

            if key in TRACKED_SOURCES:
                if not isinstance(track, str) or not track.strip():
                    problems.append(
                        f"{stack_path}.track: {key} names carry an orbit track, so a stack must "
                        f"declare one; got {track!r}"
                    )
                if direction not in FLIGHT_DIRECTIONS:
                    problems.append(
                        f"{stack_path}.direction: expected one of {list(FLIGHT_DIRECTIONS)}, "
                        f"got {direction!r}"
                    )
            else:
                # Sentinel-1 names carry no track token (see the module docstring note).
                if track is not None:
                    problems.append(
                        f"{stack_path}.track: {key} names carry no track token, so "
                        f"parse_granule yields None; a declared track {track!r} cannot be verified"
                    )
                if direction is not None and direction not in FLIGHT_DIRECTIONS:
                    problems.append(
                        f"{stack_path}.direction: expected null (unparsed) or one of "
                        f"{list(FLIGHT_DIRECTIONS)}, got {direction!r}"
                    )

            parsed_times: list[str] = ["" for _ in granule_ids]
            for position, granule_id in enumerate(granule_ids):
                id_path = f"{stack_path}.granule_ids[{position}]"
                if not isinstance(granule_id, str) or not granule_id.strip():
                    problems.append(f"{id_path}: empty granule id ({granule_id!r})")
                    continue
                parsed = parse_granule(granule_id)
                if parsed.level is None:
                    problems.append(
                        f"{id_path}: {granule_id!r} does not parse with the module's grammar"
                    )
                if (parsed.track, parsed.direction) != (track, direction):
                    problems.append(
                        f"{id_path}: {granule_id!r} parses to track {parsed.track!r}/"
                        f"direction {parsed.direction!r}, but the stack declares "
                        f"{track!r}/{direction!r}"
                    )
                if granule_id not in source_id_set:
                    problems.append(
                        f"{id_path}: {granule_id!r} is not in {base}.granule_ids, so `download` "
                        "has no url/size record for it"
                    )
                parsed_times[position] = parsed.reference_start or ""

            if any(not value for value in parsed_times):
                missing_times = [
                    granule_ids[position]
                    for position, value in enumerate(parsed_times)
                    if not value
                ]
                problems.append(
                    f"{stack_path}.granule_ids: no acquisition timestamp in {missing_times[:3]!r} "
                    "(cannot check chronological order)"
                )
            else:
                for position in range(1, len(parsed_times)):
                    if parsed_times[position] < parsed_times[position - 1]:
                        problems.append(
                            f"{stack_path}.granule_ids[{position}]: not chronological — "
                            f"{parsed_times[position]!r} follows {parsed_times[position - 1]!r}"
                        )
                        break

                # Even sampling must keep both ends of the advertised window: a plan that fetches
                # 12 ids labelled 2023..2026 must actually contain the first and last acquisition.
                if window is not None:
                    ordered = stack.get("date_range") or [None, None]
                    if parsed_times[0] != ordered[0] or parsed_times[-1] != ordered[1]:
                        problems.append(
                            f"{stack_path}.date_range: advertises {ordered!r} but the sampled "
                            f"granule_ids span {parsed_times[0]!r}..{parsed_times[-1]!r}; "
                            "the first and last granules of the stack do not appear in "
                            "granule_ids"
                        )

        # Documented order: most granules first, ties broken by most recent acquisition.
        ranks = [stack_rank(stack) for stack in stacks if isinstance(stack, dict)]
        if ranks != sorted(ranks, reverse=True):
            problems.append(
                f"{base}.stacks: not ordered largest-first/tie-most-recent ({ranks!r})"
            )

        if isinstance(recommended, dict):
            fingerprints = [
                stack_fingerprint(stack) for stack in stacks if isinstance(stack, dict)
            ]
            matches = fingerprints.count(stack_fingerprint(recommended))
            if matches != 1:
                problems.append(
                    f"{base}.recommended_stack: must equal exactly one entry in {base}.stacks, "
                    f"matched {matches} (track {recommended.get('track')!r}/"
                    f"direction {recommended.get('direction')!r}, "
                    f"n_granules {recommended.get('n_granules')!r})"
                )

            identified = [
                stack
                for stack in stacks
                if isinstance(stack, dict) and stack.get("track") is not None
            ]
            pool = identified or [stack for stack in stacks if isinstance(stack, dict)]
            if pool:
                expected = max(pool, key=stack_rank)
                if stack_fingerprint(expected) != stack_fingerprint(recommended):
                    problems.append(
                        f"{base}.recommended_stack: the module's rule is the largest identified "
                        f"stack, ties by most recent; expected track {expected.get('track')!r}/"
                        f"{expected.get('direction')!r} n_granules {expected.get('n_granules')!r} "
                        f"ending {(expected.get('date_range') or [None, None])[1]!r}, got track "
                        f"{recommended.get('track')!r}/{recommended.get('direction')!r} "
                        f"n_granules {recommended.get('n_granules')!r} ending "
                        f"{(recommended.get('date_range') or [None, None])[1]!r}"
                    )

    assert_no_problems(case, "stack consistency", problems)


