@pytest.mark.parametrize("case", CASES)
def test_report_shape(case: str) -> None:
    report, _ = load_report(case)
    problems: list[str] = []

    contract_version = report.get("contract_version")
    if contract_version != M.CONTRACT_VERSION:
        problems.append(
            f"contract_version: expected {M.CONTRACT_VERSION!r} (what `search` writes), "
            f"got {contract_version!r}"
        )

    city = report.get("city")
    if city != case:
        problems.append(f"city: expected {case!r} (the file name), got {city!r}")

    bbox = report.get("aoi_bbox")
    if not isinstance(bbox, list) or len(bbox) != 4 or not all(is_number(value) for value in bbox):
        problems.append(f"aoi_bbox: expected 4 numbers [west, south, east, north], got {bbox!r}")
    else:
        west, south, east, north = bbox
        if not west < east:
            problems.append(f"aoi_bbox: west {west!r} is not < east {east!r} (ordering W,S,E,N)")
        if not south < north:
            problems.append(
                f"aoi_bbox: south {south!r} is not < north {north!r} (ordering W,S,E,N)"
            )

    timestamp(case, "generated_utc", report.get("generated_utc"), problems)

    sources = report.get("sources")
    if not isinstance(sources, dict):
        problems.append(f"sources: expected an object keyed by source, got {sources!r}")
        sources = {}
    missing_sources = [key for key in REQUIRED_SOURCES if key not in sources]
    if missing_sources:
        problems.append(f"sources: missing probe(s) {missing_sources}; got {sorted(sources)}")

    chosen = report.get("chosen_source")
    if not isinstance(chosen, str) or not chosen.strip():
        problems.append(f"chosen_source: expected a non-empty string, got {chosen!r}")
    elif chosen in CHOSEN_TO_SOURCE:
        source_key = CHOSEN_TO_SOURCE[chosen]
        entry = sources.get(source_key) or {}
        if not entry.get("available"):
            problems.append(
                f"chosen_source: {chosen!r} claims sources.{source_key}, but "
                f"sources.{source_key}.available is {entry.get('available')!r}"
            )
    elif chosen != "MOCK":
        problems.append(
            f"chosen_source: {chosen!r} is neither one of {sorted(CHOSEN_TO_SOURCE)} nor 'MOCK'"
        )

    provenance = report.get("provenance")
    if not isinstance(provenance, dict):
        problems.append(f"provenance: expected an object, got {provenance!r}")
    else:
        missing_keys = [key for key in C.PROVENANCE_REQUIRED_KEYS if key not in provenance]
        if missing_keys:
            problems.append(
                f"provenance: missing keys required by contracts.PROVENANCE_REQUIRED_KEYS "
                f"{missing_keys}; present {sorted(provenance)}"
            )
        source_label = provenance.get("source")
        if not isinstance(source_label, str) or not source_label.strip():
            problems.append(f"provenance.source: expected a non-empty string, got {source_label!r}")

    assert_no_problems(case, "availability evidence shape", problems)


