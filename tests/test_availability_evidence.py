@pytest.mark.parametrize("case", CASES)
def test_source_honesty(case: str) -> None:
    report, _ = load_report(case)
    sources = report.get("sources")
    if not isinstance(sources, dict):
        pytest.fail(f"{case}: {report_path(case)}: sources is not an object ({sources!r})")

    eu = eu_member_state(case)
    problems: list[str] = []

    for key in REQUIRED_SOURCES:
        src = sources.get(key)
        base = f"sources.{key}"
        if not isinstance(src, dict):
            problems.append(f"{base}: missing or not an object (got {src!r})")
            continue

        missing = [field for field in SOURCE_FIELDS if field not in src]
        if missing:
            problems.append(f"{base}: missing required field(s) {missing}")

        attempted = src.get("attempted")
        if not isinstance(attempted, bool):
            problems.append(f"{base}.attempted: expected a bool, got {attempted!r}")

        available = src.get("available")
        if not (available is None or isinstance(available, bool)):
            problems.append(f"{base}.available: expected true/false/null, got {available!r}")
            available = None

        n_granules = src.get("n_granules")
        if n_granules is not None and (
            not isinstance(n_granules, int) or isinstance(n_granules, bool)
        ):
            problems.append(f"{base}.n_granules: expected an int or null, got {n_granules!r}")
            n_granules = None

        window = date_range(
            case, f"{base}.date_range", src.get("date_range"), problems, allow_none=True
        )

        samples = src.get("sample_granules")
        if not isinstance(samples, list):
            problems.append(f"{base}.sample_granules: expected a list, got {samples!r}")

        note = src.get("coverage_note")
        if not isinstance(note, str) or not note.strip():
            problems.append(f"{base}.coverage_note: expected a non-empty string, got {note!r}")

        error = src.get("error")
        if error is not None and not isinstance(error, str):
            problems.append(f"{base}.error: expected a string or null, got {error!r}")

        if available is False:
            if n_granules != 0:
                problems.append(
                    f"{base}.n_granules: available is false but n_granules is "
                    f"{n_granules!r} (must be 0)"
                )
            if window is not None:
                problems.append(
                    f"{base}.date_range: available is false but date_range is "
                    f"{src.get('date_range')!r} (must be null: no granules, no window)"
                )
            for field in ("sample_granules", "granule_ids", "stacks"):
                entries = src.get(field) or []
                if entries:
                    problems.append(
                        f"{base}.{field}: available is false but carries {len(entries)} entr(ies): "
                        f"{str(entries[0])[:120]!r}"
                    )
        elif available is True:
            if not isinstance(n_granules, int) or n_granules <= 0:
                problems.append(
                    f"{base}.n_granules: available is true but n_granules is "
                    f"{n_granules!r} (must be > 0)"
                )
            if window is None:
                problems.append(
                    f"{base}.date_range: available is true but date_range is "
                    f"{src.get('date_range')!r} (must be [start, stop])"
                )
        elif key != "egms":
            problems.append(
                f"{base}.available: a scripted probe reported null; only egms may be unknown "
                f"(got {available!r})"
            )

        if key == "egms":
            if available is not None:
                problems.append(
                    f"{base}.available: EGMS is a manual portal download, never a scripted "
                    f"verdict; must stay null, got {available!r}"
                )
            if "manual" not in src:
                problems.append(f"{base}.manual: missing (EGMS evidence must say it is manual)")
            elif eu and src.get("manual") is not True:
                problems.append(
                    f"{base}.manual: {case!r} is an EU member state ({eu!r}), so EGMS is eligible "
                    f"by hand and manual must be true, got {src.get('manual')!r}"
                )
            if n_granules is not None:
                problems.append(
                    f"{base}.n_granules: EGMS was never probed, so the count must stay null, "
                    f"got {n_granules!r}"
                )

    assert_no_problems(case, "per-source honesty", problems)


