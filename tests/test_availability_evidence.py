@pytest.mark.parametrize("case", CASES)
def test_download_plan_matches_recommended_stack(case: str) -> None:
    report, _ = load_report(case)
    chosen = report.get("chosen_source")
    source = CHOSEN_TO_SOURCE.get(str(chosen))
    if source is None:
        pytest.skip(
            f"{case}: chosen_source is {chosen!r} (mock path), so no scraped source has a "
            "recommendation to plan"
        )
    src = (report.get("sources") or {}).get(source) or {}
    if not src.get("available"):
        pytest.skip(
            f"{case}: sources.{source}.available is {src.get('available')!r}; there is no "
            "recommended stack to plan"
        )
    recommended = src.get("recommended_stack")
    if not isinstance(recommended, dict) or not recommended.get("granule_ids"):
        pytest.skip(
            f"{case}: sources.{source} has no recommended_stack; re-run `search` to persist "
            "stacks (not done here: the suite is offline)"
        )

    before = files_under(RAW)
    command = [
        sys.executable,
        str(PIPELINE),
        "download",
        "--city",
        case,
        "--source",
        source,
        "--stack",
        "recommended",
        "--dry-run",
        # Generous cap on purpose: the budget guard has its own tests, and Sentinel-1 stacks are
        # ~48-61 GB of known size. This test is about identity and geometry, not bytes.
        "--max-gb",
        "100",
        "--availability",
        str(AVAILABILITY),
        "--raw",
        str(RAW),
    ]
    completed = subprocess.run(
        command, cwd=ROOT, capture_output=True, text=True, timeout=120, env=dict(os.environ)
    )
    after = files_under(RAW)
    output = f"{completed.stdout}\n{completed.stderr}"

    context = f"{case}: `download --source {source} --stack recommended --dry-run`\n{output}"
    assert completed.returncode == 0, (
        f"{context}\nexpected exit 0 (RC_OK), got {completed.returncode}"
    )
    assert "REFUSED" not in output, f"{context}\nthe guard refused the recommended stack"
    assert "dry run: nothing written" in completed.stdout, (
        f"{context}\nthe dry run did not confirm it wrote nothing"
    )

    planned = PLAN_ITEM_RE.findall(completed.stdout)
    expected_ids = [str(gid) for gid in recommended["granule_ids"]]
    assert planned == expected_ids, (
        f"{context}\nplanned {len(planned)} granule(s) {planned[:3]!r}...; the recommended stack "
        f"carries {len(expected_ids)} {expected_ids[:3]!r}... (in order)"
    )

    summary = PLAN_SUMMARY_RE.search(completed.stdout)
    assert summary is not None, (
        f"{context}\nno `plan: N granule(s), ..., K geometry/geometries` line"
    )
    plan_count, geometry_count = int(summary.group(1)), int(summary.group(2))
    assert plan_count == len(expected_ids), (
        f"{context}\nplan summary counts {plan_count} granule(s), expected {len(expected_ids)}"
    )
    assert geometry_count == 1, (
        f"{context}\nplan spans {geometry_count} acquisition geometries; a single-geometry stack "
        f"must report exactly 1"
    )

    planned_geometries = {
        (parse_granule(gid).track, parse_granule(gid).direction) for gid in planned
    }
    assert planned_geometries == {(recommended.get("track"), recommended.get("direction"))}, (
        f"{context}\nplanned ids parse to geometries {sorted(planned_geometries)!r}; the "
        f"recommended stack declares ({recommended.get('track')!r}, "
        f"{recommended.get('direction')!r})"
    )

    new_files = sorted(str(path.relative_to(ROOT)) for path in after - before)
    assert not new_files, (
        f"{context}\nthe dry run wrote under data/raw (expected nothing): {new_files[:5]!r}"
    )


