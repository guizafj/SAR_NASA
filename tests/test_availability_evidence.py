# Helpers: every failure names the case, the JSON path and the offending value
# =============================================================================================


def report_path(case: str) -> pathlib.Path:
    return AVAILABILITY / f"{case}.json"


def load_report(case: str) -> tuple[dict, str]:
    """Read one committed report. A missing report is skipped, corrupt JSON is a failure."""
    path = report_path(case)
    if not path.exists():
        pytest.skip(
            f"{case}: no committed availability report at {path}; regenerating it needs the "
            "network (and is not done in this offline suite)"
        )
    text = path.read_text()
    try:
        report = json.loads(text)
    except json.JSONDecodeError as exc:
        pytest.fail(f"{case}: {path}: committed availability evidence is not valid JSON: {exc}")
    if not isinstance(report, dict):
        pytest.fail(
            f"{case}: {path}: expected a JSON object at the top level, "
            f"got {type(report).__name__}"
        )
    return report, text


def assert_no_problems(case: str, headline: str, problems: list[str]) -> None:
    assert not problems, (
        f"{case}: {headline} — {report_path(case)}\n"
        + "\n".join(f"  - {problem}" for problem in problems)
    )


def is_number(value: Any) -> bool:
    return isinstance(value, (int, float)) and not isinstance(value, bool)


def timestamp(case: str, json_path: str, value: Any, problems: list[str]) -> dt.datetime | None:
    """Parse an ISO-8601 ``Z`` timestamp or record a problem that names the bad value."""
    if not isinstance(value, str):
        problems.append(f"{json_path}: expected an ISO-8601 UTC timestamp, got {value!r}")
        return None
    if not ISO_UTC_RE.match(value):
        problems.append(f"{json_path}: not an ISO-8601 UTC timestamp ({value!r})")
        return None
    try:
        return dt.datetime.strptime(value, ISO_UTC_FMT).replace(tzinfo=dt.timezone.utc)
    except ValueError as exc:  # e.g. 2026-13-40T99:99:99Z
        problems.append(f"{json_path}: not a real timestamp ({value!r}: {exc})")
        return None


def date_range(
    case: str,
    json_path: str,
    value: Any,
    problems: list[str],
    *,
    allow_none: bool,
) -> tuple[dt.datetime, dt.datetime] | None:
    """Validate ``[start, stop]``: two ISO timestamps, ordered. Returns parsed datetimes."""
    if value is None:
        if not allow_none:
            problems.append(f"{json_path}: expected [start, stop], got null")
        return None
    if not isinstance(value, list) or len(value) != 2:
        problems.append(
            f"{json_path}: expected [start, stop] with two ISO timestamps, got {value!r}"
        )
        return None
    start = timestamp(case, f"{json_path}[0]", value[0], problems)
    stop = timestamp(case, f"{json_path}[1]", value[1], problems)
    if start is None or stop is None:
        return None
    if start > stop:
        problems.append(f"{json_path}: not ordered — start {value[0]!r} is after stop {value[1]!r}")
        return None
    return start, stop


def iter_granule_ids(src: dict, base: str) -> Iterator[tuple[str, Any]]:
    """Every granule id the report carries, with its JSON path."""
    for index, granule_id in enumerate(src.get("granule_ids") or []):
        yield f"{base}.granule_ids[{index}]", granule_id
    for index, sample in enumerate(src.get("sample_granules") or []):
        if isinstance(sample, dict):
            yield f"{base}.sample_granules[{index}].id", sample.get("id")
    for index, stack in enumerate(src.get("stacks") or []):
        if not isinstance(stack, dict):
            continue
        for position, granule_id in enumerate(stack.get("granule_ids") or []):
            yield f"{base}.stacks[{index}].granule_ids[{position}]", granule_id
    for index, granule in enumerate(src.get("granules") or []):
        if isinstance(granule, dict):
            yield f"{base}.granules[{index}].id", granule.get("id")


def stack_fingerprint(stack: dict) -> str:
    """The fields that identify a stack; ``recommended_stack`` is a stack plus a ``why`` note."""
    return json.dumps([stack.get(key) for key in STACK_FIELDS], sort_keys=True)


def stack_rank(stack: dict) -> tuple[float, str]:
    """The module's documented order: most granules first, ties broken by most recent."""
    n_granules = stack.get("n_granules")
    end = (stack.get("date_range") or ["", ""])[1]
    return (n_granules if is_number(n_granules) else 0, end if isinstance(end, str) else "")


def eu_member_state(case: str) -> Any:
    """``pipeline/ingest/aois.json`` is the config ``search`` probes; it says who EGMS covers."""
    try:
        cities = json.loads(AOIS.read_text()).get("cities") or {}
        return (cities.get(case) or {}).get("eu_member_state")
    except (OSError, json.JSONDecodeError):
        return None


def files_under(root: pathlib.Path) -> set[pathlib.Path]:
    return {path for path in root.rglob("*") if path.is_file()} if root.exists() else set()


