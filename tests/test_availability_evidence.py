@pytest.mark.parametrize("case", CASES)
def test_freshness(case: str) -> None:
    report, _ = load_report(case)
    candidates: list[tuple[str, Any]] = [("generated_utc", report.get("generated_utc"))]
    provenance = report.get("provenance")
    if isinstance(provenance, dict) and "retrieved_utc" in provenance:
        candidates.append(("provenance.retrieved_utc", provenance.get("retrieved_utc")))
    for key, src in (report.get("sources") or {}).items():
        if not isinstance(src, dict):
            continue
        window = src.get("date_range")
        if isinstance(window, list) and len(window) == 2:
            candidates.append((f"sources.{key}.date_range[1]", window[1]))
        for index, stack in enumerate(src.get("stacks") or []):
            if not isinstance(stack, dict):
                continue
            stack_window = stack.get("date_range")
            if isinstance(stack_window, list) and len(stack_window) == 2:
                candidates.append(
                    (f"sources.{key}.stacks[{index}].date_range[1]", stack_window[1])
                )

    problems: list[str] = []
    now = dt.datetime.now(dt.timezone.utc)
    for json_path, value in candidates:
        parsed = timestamp(case, json_path, value, problems)
        if parsed is not None and parsed > now + FUTURE_TOLERANCE:
            problems.append(
                f"{json_path}: {value!r} is in the future (now {now.strftime(ISO_UTC_FMT)}, "
                f"tolerance {FUTURE_TOLERANCE}); real granules and reports cannot be stamped ahead"
            )

    assert_no_problems(case, "freshness", problems)


