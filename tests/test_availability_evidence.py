def walk_strings(node: Any, path: str) -> Iterator[tuple[str, str]]:
    if isinstance(node, dict):
        for key, value in node.items():
            yield from walk_strings(value, f"{path}.{key}" if path else str(key))
    elif isinstance(node, list):
        for index, value in enumerate(node):
            yield from walk_strings(value, f"{path}[{index}]")
    elif isinstance(node, str):
        yield path, node


@pytest.mark.parametrize("case", CASES)
def test_no_secrets(case: str) -> None:
    report, text = load_report(case)
    problems: list[str] = []

    for json_path, value in walk_strings(report, ""):
        field = json_path.rsplit(".", 1)[-1].split("[", 1)[0]
        if SECRET_FIELD_RE.search(field):
            problems.append(f"{json_path}: field name looks like a secret ({field!r})")
        signature = QUERY_SIGNATURE_RE.search(value)
        if signature:
            problems.append(
                f"{json_path}: presigned-URL query signature in {value[:200]!r} "
                f"(matched {signature.group(0)[:80]!r})"
            )

    for marker in PRESIGNED_MARKERS:
        if marker.lower() in text.lower():
            problems.append(f"raw JSON text: presigned-URL marker {marker!r} present")

    password = os.environ.get("EARTHDATA_PASS")
    if password and len(password) >= 6 and password in text:
        # Never echo the value itself: the point is that it must not be in the file.
        problems.append(
            "raw JSON text: contains the current EARTHDATA_PASS value (redacted) — "
            "a committed report must never carry credentials"
        )

    assert_no_problems(case, "no secrets in the evidence", problems)
