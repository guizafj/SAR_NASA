"""Pin the committed availability evidence in ``data/processed/_availability/{case}.json``.

That JSON is what ``README`` §5, ``docs/data-source-decision.md``, ``docs/first-granule-runbook.md``
§2 and ``download --stack recommended`` all cite: it is committed, regenerated by a network call,
and until now nothing verified its shape. A malformed stack in there silently produces an
unusable download plan (mixed geometries, ids without urls, a window the fetch does not cover).

These tests read the committed JSON only. No network, no regeneration, no writes outside pytest's
``tmp_path``: the dry-run in test 5 runs the real CLI with ``sys.executable`` and is checked to
leave ``data/raw`` untouched.

Granule identity is parsed with the module's own grammar (``parse_granule``/``ParsedGranule``),
never re-implemented here, so a change to the grammar and a change to the evidence cannot drift.

One grammar note: Sentinel-1 names (``S1A_IW_SLC__1SDV_...``) carry no orbit-track token, so
``parse_granule`` returns ``track=None`` for every S1 id, and ``direction`` is often unparsed too.
Test 4 therefore requires every stack's declared ``(track, direction)`` to equal the parsed value
of *every* id in it, and requires a non-null track only for sources whose names can express one
(NISAR, OPERA). Anything the grammar can express must be consistent; nothing is invented.
"""

