@pytest.mark.parametrize("case", CASES)
def test_granule_identity(case: str) -> None:
    report, _ = load_report(case)
    sources = report.get("sources")
    if not isinstance(sources, dict):
        pytest.fail(f"{case}: {report_path(case)}: sources is not an object ({sources!r})")

    problems: list[str] = []
    for key, src in sources.items():
        if not isinstance(src, dict):
            continue
        for json_path, granule_id in iter_granule_ids(src, f"sources.{key}"):
            if not isinstance(granule_id, str) or not granule_id.strip():
                problems.append(f"{json_path}: empty granule id ({granule_id!r})")
                continue
            parsed = parse_granule(granule_id)
            if parsed.level is None or parsed.product is None:
                problems.append(
                    f"{json_path}: {granule_id!r} does not parse with the module's grammar "
                    f"(level={parsed.level!r}, product={parsed.product!r})"
                )
                continue
            if key == "nisar_gunw" and (parsed.level, parsed.product) != ("L2", "GUNW"):
                problems.append(
                    f"{json_path}: {granule_id!r} parses to level {parsed.level}/product "
                    f"{parsed.product}; nisar_gunw evidence must be L2 GUNW (an L0 RRSD or L1 RSLC "
                    "means the wrong product was probed)"
                )
            if key == "sentinel1_slc" and (parsed.level, parsed.product) != ("S1", "SLC"):
                problems.append(
                    f"{json_path}: {granule_id!r} parses to level {parsed.level}/product "
                    f"{parsed.product}; sentinel1_slc evidence must be S1 SLC"
                )

    assert_no_problems(case, "granule identity", problems)


